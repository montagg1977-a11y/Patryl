import { Modal } from './Modal';

interface LegalModalProps {
  open: boolean;
  onClose: () => void;
  type: 'offer' | 'privacy' | 'subscription';
}

export function LegalModal({ open, onClose, type }: LegalModalProps) {
  const titles: Record<string, string> = {
    offer: 'Публічна оферта',
    privacy: 'Політика конфіденційності',
    subscription: 'Керування підпискою',
  };

  return (
    <Modal open={open} onClose={onClose} title={titles[type] ?? ''}>
      {type === 'offer' && <OfferText />}
      {type === 'privacy' && <PrivacyText />}
      {type === 'subscription' && <SubscriptionText />}
    </Modal>
  );
}

